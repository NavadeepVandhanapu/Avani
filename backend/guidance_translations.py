def get_localized_guidance_entry(key: str, fallback_ref: Dict[str, Any], language: str = "en") -> Dict[str, Any]:
    """
    Retrieves full localized guidance entry for key and language.
    If language is 'en', returns fallback_ref directly.
    For 'te' or 'hi', injects translated fields, falling back gracefully to localized generic guidance.
    """
    if language == "en":
        return fallback_ref

    # Check if exact key exists in translations
    matched_trans = None
    if key in GUIDANCE_TEXT_TRANSLATIONS and language in GUIDANCE_TEXT_TRANSLATIONS[key]:
        matched_trans = GUIDANCE_TEXT_TRANSLATIONS[key][language]
    else:
        # Check alias keys or partial keys
        for k, trans_dict in GUIDANCE_TEXT_TRANSLATIONS.items():
            if k in key or key in k:
                if language in trans_dict:
                    matched_trans = trans_dict[language]
                    break

    # If no specific translation exists for this disease, fall back to GENERIC_CROP_GUIDANCE translations
    if not matched_trans:
        generic_dict = GUIDANCE_TEXT_TRANSLATIONS.get("GENERIC_CROP_GUIDANCE", {})
        matched_trans = generic_dict.get(language, {})

    # Construct localized entry
    localized = dict(fallback_ref)
    
    localized["crop"] = get_localized_crop(fallback_ref.get("crop", "General Crop"), language)
    localized["condition"] = get_localized_condition(fallback_ref.get("condition", "Foliage Inspection"), language)
    localized["category"] = get_localized_category(fallback_ref.get("category", "General"), language)
    
    if "plain_summary" in matched_trans:
        localized["plain_summary"] = matched_trans["plain_summary"]
    elif language in FALLBACK_MESSAGES:
        localized["plain_summary"] = FALLBACK_MESSAGES[language]
        
    if "visible_symptoms" in matched_trans:
        localized["visible_symptoms"] = list(matched_trans["visible_symptoms"])
    elif language in FALLBACK_MESSAGES:
        localized["visible_symptoms"] = [FALLBACK_MESSAGES[language]]

    if "what_to_check_now" in matched_trans:
        localized["what_to_check_now"] = list(matched_trans["what_to_check_now"])
    elif language in FALLBACK_MESSAGES:
        localized["what_to_check_now"] = [FALLBACK_MESSAGES[language]]

    if "what_to_monitor" in matched_trans:
        localized["what_to_monitor"] = list(matched_trans["what_to_monitor"])
    elif language in FALLBACK_MESSAGES:
        localized["what_to_monitor"] = [FALLBACK_MESSAGES[language]]

    if "when_to_seek_help" in matched_trans:
        localized["when_to_seek_help"] = list(matched_trans["when_to_seek_help"])
    elif language in FALLBACK_MESSAGES:
        localized["when_to_seek_help"] = [FALLBACK_MESSAGES[language]]

    if "timeline_actions" in matched_trans:
        localized["timeline_actions"] = list(matched_trans["timeline_actions"])
    elif language in ("te", "hi"):
        # Prevent English task descriptions from leaking into regional languages
        generic_trans = GUIDANCE_TEXT_TRANSLATIONS.get("GENERIC_CROP_GUIDANCE", {}).get(language, {})
        if "timeline_actions" in generic_trans:
            localized["timeline_actions"] = list(generic_trans["timeline_actions"])
        else:
            localized["timeline_actions"] = []
    else:
        # Translate periods in existing timeline actions if available
        new_timeline = []
        for item in fallback_ref.get("timeline_actions", []):
            period_en = item.get("period", "Today")
            period_loc = PERIODS_LOCALIZED.get(period_en, {}).get(language, period_en)
            new_timeline.append({
                "period": period_loc,
                "task": item.get("task", "")
            })
        localized["timeline_actions"] = new_timeline

    if "safety_note" in matched_trans:
        localized["safety_note"] = matched_trans["safety_note"]
    elif language in FALLBACK_MESSAGES:
        localized["safety_note"] = FALLBACK_MESSAGES[language]

    return localized
